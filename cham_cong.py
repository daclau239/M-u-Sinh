def authenticate(username, password):
    try:
        rows = sb_request(
            "GET",
            "users",
            params={
                "select": "*",
                "username": f"eq.{username.strip()}",
                "active": "eq.true",
                "limit": "1",
            },
        )

        if not rows:
            return None

        user = rows[0]

        if hmac.compare_digest(
            user["password_hash"],
            hash_password(password),
        ):
            return user

        return None

    except Exception:
        return None


