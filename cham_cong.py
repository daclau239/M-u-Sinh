def make_excel(df):
    output = io.BytesIO()

    with pd.ExcelWriter(
        output,
        engine="openpyxl"
    ) as writer:
        df.to_excel(
            writer,
            index=False,
            sheet_name="BangCong"
        )

        ws = writer.book["BangCong"]

        for cells in ws.columns:
            max_length = 0
            letter = cells[0].column_letter

            for cell in cells:
                value = "" if cell.value is None else str(cell.value)
                max_length = max(
                    max_length,
                    len(value)
                )

            ws.column_dimensions[letter].width = min(
                max(max_length + 2, 12),
                35,
            )

    output.seek(0)
    return output.getvalue()


